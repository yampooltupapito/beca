-- Eliminación limpia de tablas previas en orden inverso de dependencias
DROP TABLE IF EXISTS bitacora_evento CASCADE;
DROP TABLE IF EXISTS postulacion_seleccion CASCADE;
DROP TABLE IF EXISTS postulante CASCADE;
DROP TABLE IF EXISTS programa_estudio CASCADE;
DROP TABLE IF EXISTS institucion CASCADE;
DROP TABLE IF EXISTS etapa CASCADE;
DROP TABLE IF EXISTS modalidad CASCADE;
DROP TABLE IF EXISTS usuario CASCADE;
DROP TABLE IF EXISTS parametro_sistema CASCADE;

-- -----------------------------------------------------------------------------
-- 1. Tabla: parametro_sistema (Fecha de corte parametrizable RN-02 y otros)
-- -----------------------------------------------------------------------------
CREATE TABLE parametro_sistema (
    clave VARCHAR(50) NOT NULL,
    valor VARCHAR(150) NOT NULL,
    descripcion VARCHAR(255) NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_parametro_sistema PRIMARY KEY (clave)
);

-- -----------------------------------------------------------------------------
-- 2. Tabla: usuario (Entidad 1 - Autenticación y control de roles RF-01, RF-02)
-- -----------------------------------------------------------------------------
CREATE TABLE usuario (
    id_usuario INT GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(50) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL,
    activo SMALLINT NOT NULL DEFAULT 1,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_username UNIQUE (username),
    CONSTRAINT chk_usuario_rol CHECK (rol IN ('ADMINISTRADOR', 'POSTULANTE')),
    CONSTRAINT chk_usuario_activo CHECK (activo IN (0, 1))
);

CREATE INDEX idx_usuario_rol ON usuario (rol);

-- -----------------------------------------------------------------------------
-- 3. Tabla: modalidad (Entidad 2 - 9 Modalidades de Beca 18 RN-02, RN-09)
-- -----------------------------------------------------------------------------
CREATE TABLE modalidad (
    id_modalidad INT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    edad_maxima INT NULL,
    puntaje_minimo_enp INT NOT NULL,
    descripcion VARCHAR(255) NULL,
    CONSTRAINT pk_modalidad PRIMARY KEY (id_modalidad),
    CONSTRAINT uq_modalidad_codigo UNIQUE (codigo),
    CONSTRAINT uq_modalidad_nombre UNIQUE (nombre),
    CONSTRAINT chk_modalidad_tipo CHECK (tipo IN ('ORDINARIA', 'ESPECIAL')),
    CONSTRAINT chk_modalidad_puntaje CHECK (puntaje_minimo_enp BETWEEN 0 AND 120)
);

-- -----------------------------------------------------------------------------
-- 4. Tabla: etapa (Entidad 3 - Cronograma parametrizable y publicación RF-12, RN-13)
-- -----------------------------------------------------------------------------
CREATE TABLE etapa (
    id_etapa INT GENERATED BY DEFAULT AS IDENTITY,
    orden INT NOT NULL,
    codigo VARCHAR(40) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    fecha_referencia VARCHAR(80) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    publicada SMALLINT NOT NULL DEFAULT 0,
    descripcion VARCHAR(255) NULL,
    CONSTRAINT pk_etapa PRIMARY KEY (id_etapa),
    CONSTRAINT uq_etapa_orden UNIQUE (orden),
    CONSTRAINT uq_etapa_codigo UNIQUE (codigo),
    CONSTRAINT chk_etapa_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT chk_etapa_publicada CHECK (publicada IN (0, 1))
);

-- -----------------------------------------------------------------------------
-- 5. Tabla: institucion (Entidad 5A - Instituciones de Educación Superior RF-13)
-- -----------------------------------------------------------------------------
CREATE TABLE institucion (
    id_institucion INT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(150) NOT NULL,
    tipo_gestion VARCHAR(20) NOT NULL,
    region VARCHAR(80) NOT NULL,
    elegible SMALLINT NOT NULL DEFAULT 1,
    CONSTRAINT pk_institucion PRIMARY KEY (id_institucion),
    CONSTRAINT uq_institucion_nombre UNIQUE (nombre),
    CONSTRAINT chk_institucion_gestion CHECK (tipo_gestion IN ('PUBLICA', 'PRIVADA')),
    CONSTRAINT chk_institucion_elegible CHECK (elegible IN (0, 1))
);

-- -----------------------------------------------------------------------------
-- 6. Tabla: programa_estudio (Entidad 5B - Programas y vacantes RF-13, RN-11)
-- -----------------------------------------------------------------------------
CREATE TABLE programa_estudio (
    id_programa INT GENERATED BY DEFAULT AS IDENTITY,
    id_institucion INT NULL,
    institucion VARCHAR(150) NOT NULL,
    programa_estudios VARCHAR(150) NOT NULL,
    tipo_gestion VARCHAR(20) NOT NULL,
    region VARCHAR(80) NOT NULL,
    vacantes INT NOT NULL,
    activo SMALLINT NOT NULL DEFAULT 1,
    CONSTRAINT pk_programa_estudio PRIMARY KEY (id_programa),
    CONSTRAINT fk_programa_institucion FOREIGN KEY (id_institucion)
        REFERENCES institucion (id_institucion)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT uq_institucion_programa UNIQUE (institucion, programa_estudios),
    CONSTRAINT chk_programa_gestion CHECK (tipo_gestion IN ('PUBLICA', 'PRIVADA')),
    CONSTRAINT chk_programa_vacantes CHECK (vacantes >= 1)
);

CREATE INDEX idx_programa_region ON programa_estudio (region);
CREATE INDEX idx_programa_gestion ON programa_estudio (tipo_gestion);

-- -----------------------------------------------------------------------------
-- 7. Tabla: postulante (Entidad 4 - Datos de inscripción, estado y ENP RF-03..RF-11)
-- -----------------------------------------------------------------------------
CREATE TABLE postulante (
    id_postulante INT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario INT NOT NULL,
    dni CHAR(8) NOT NULL,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    edad_corte INT NOT NULL,
    nacionalidad VARCHAR(50) NOT NULL DEFAULT 'PERUANA',
    correo VARCHAR(120) NOT NULL,
    celular CHAR(9) NOT NULL,
    region VARCHAR(80) NOT NULL,
    colegio VARCHAR(150) NOT NULL,
    situacion_estudios VARCHAR(30) NOT NULL,
    anio_egreso INT NOT NULL,
    tercio_superior SMALLINT NOT NULL DEFAULT 0,
    clasificacion_socioeconomica VARCHAR(30) NOT NULL,
    discapacidad_acreditada SMALLINT NOT NULL DEFAULT 0,
    id_modalidad INT NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'INSCRITO',
    observacion_revision TEXT NULL,
    puntaje_enp NUMERIC(5,2) NULL,
    fecha_inscripcion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_postulante PRIMARY KEY (id_postulante),
    CONSTRAINT uq_postulante_usuario UNIQUE (id_usuario),
    CONSTRAINT uq_postulante_dni UNIQUE (dni),
    CONSTRAINT fk_postulante_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_postulante_modalidad FOREIGN KEY (id_modalidad)
        REFERENCES modalidad (id_modalidad)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_postulante_situacion CHECK (situacion_estudios IN ('CURSANDO_5TO', 'EGRESADO')),
    CONSTRAINT chk_postulante_cse CHECK (clasificacion_socioeconomica IN ('POBREZA_EXTREMA', 'POBREZA', 'VULNERABLE', 'NO_POBRE')),
    CONSTRAINT chk_postulante_estado CHECK (estado IN (
        'INSCRITO',
        'EN REVISION',
        'APTO',
        'NO APTO',
        'PRESELECCIONADO',
        'NO PRESELECCIONADO',
        'POSTULO A SELECCION',
        'SELECCIONADO',
        'NO SELECCIONADO'
    )),
    CONSTRAINT chk_postulante_puntaje CHECK (puntaje_enp IS NULL OR (puntaje_enp >= 0 AND puntaje_enp <= 120)),
    CONSTRAINT chk_postulante_tercio CHECK (tercio_superior IN (0, 1)),
    CONSTRAINT chk_postulante_discapacidad CHECK (discapacidad_acreditada IN (0, 1))
);

CREATE INDEX idx_postulante_modalidad ON postulante (id_modalidad);
CREATE INDEX idx_postulante_estado ON postulante (estado);
CREATE INDEX idx_postulante_dni ON postulante (dni);

-- -----------------------------------------------------------------------------
-- 8. Tabla: postulacion_seleccion (Entidad 6 - Postulación a programas y ranking RF-08, RF-14)
-- -----------------------------------------------------------------------------
CREATE TABLE postulacion_seleccion (
    id_postulacion INT GENERATED BY DEFAULT AS IDENTITY,
    id_postulante INT NOT NULL,
    id_programa INT NOT NULL,
    momento INT NOT NULL,
    fecha_hora TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    orden_merito INT NULL,
    resultado VARCHAR(25) NOT NULL DEFAULT 'PENDIENTE',
    CONSTRAINT pk_postulacion_seleccion PRIMARY KEY (id_postulacion),
    CONSTRAINT uq_postulacion_postulante UNIQUE (id_postulante),
    CONSTRAINT fk_postulacion_postulante FOREIGN KEY (id_postulante)
        REFERENCES postulante (id_postulante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_postulacion_programa FOREIGN KEY (id_programa)
        REFERENCES programa_estudio (id_programa)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_postulacion_momento CHECK (momento IN (1, 2)),
    CONSTRAINT chk_postulacion_resultado CHECK (resultado IN ('PENDIENTE', 'SELECCIONADO', 'NO SELECCIONADO'))
);

CREATE INDEX idx_postulacion_programa ON postulacion_seleccion (id_programa);
CREATE INDEX idx_postulacion_fecha ON postulacion_seleccion (fecha_hora);

-- -----------------------------------------------------------------------------
-- 9. Tabla auxiliar: bitacora_evento (Respaldo de auditoría junto al archivo TXT RF-16)
-- -----------------------------------------------------------------------------
CREATE TABLE bitacora_evento (
    id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo_evento VARCHAR(50) NOT NULL,
    usuario VARCHAR(50) NOT NULL,
    detalle VARCHAR(500) NOT NULL,
    CONSTRAINT pk_bitacora_evento PRIMARY KEY (id_evento)
);

CREATE INDEX idx_bitacora_fecha ON bitacora_evento (fecha_hora DESC);
